import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
const require = createRequire(process.argv[2] || import.meta.url)
const { chromium } = require('playwright')
const browser = await chromium.launch({ headless: true, channel: 'chrome' })
try {
  const context = await browser.newContext({ viewport: { width: 810, height: 1080 }, hasTouch: true })
  await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
  const page = await context.newPage(), errors = []
  page.on('pageerror', err => errors.push(err.message))
  await page.goto('http://127.0.0.1:5192/?type=recovery')
  await page.getByRole('heading', { name: 'Your courses' }).waitFor()
  await page.getByRole('link', { name: 'Parent', exact: true }).click()
  await page.getByRole('button', { name: /^Zinc/ }).click()
  await page.getByRole('link', { name: 'Parent', exact: true }).click()
  await page.getByLabel('Parent password', { exact: true }).waitFor()
  assert.equal(await page.getByLabel('New parent password').count(), 0)
  await page.getByRole('button', { name: 'Email me a password setup link' }).click()
  await page.getByRole('status').filter({ hasText: 'Check your account' }).waitFor()
  assert.equal(await page.getByRole('heading', { name: 'Family profiles' }).count(), 0)
  assert.equal(await page.evaluate(async () => (await import('/tests/recovery-backend.js')).recoveryFixture.emails), 1)
  await page.evaluate(async () => (await import('/tests/recovery-backend.js')).recoveryFixture.deliver())
  await page.getByLabel('New parent password').fill('new-test-parent-password')
  await page.getByLabel('Confirm password').fill('mismatch-test-password')
  await page.getByRole('button', { name: 'Save parent password' }).click()
  await page.getByRole('alert').filter({ hasText: 'don’t match' }).waitFor()
  assert.equal(await page.evaluate(async () => (await import('/tests/recovery-backend.js')).recoveryFixture.updates), 0)
  await page.getByLabel('Confirm password').fill('new-test-parent-password')
  await page.getByRole('button', { name: 'Save parent password' }).click()
  await page.getByLabel('Parent password', { exact: true }).waitFor()
  await page.getByLabel('Parent password', { exact: true }).fill('wrong-password')
  await page.getByRole('button', { name: 'Unlock parent controls' }).click()
  await page.getByRole('alert').waitFor()
  await page.getByLabel('Parent password', { exact: true }).fill('new-test-parent-password')
  await page.getByRole('button', { name: 'Unlock parent controls' }).click()
  await page.getByRole('button', { name: /^Zinc/ }).click()
  await page.getByRole('heading', { name: 'Your courses' }).waitFor()
  assert.equal(await page.locator('.account-email').innerText(), 'Zinc')
  await page.getByRole('link', { name: 'Parent', exact: true }).click()
  await page.getByLabel('Parent password', { exact: true }).waitFor()
  await page.screenshot({ path: '/private/tmp/home-scholar-google-parent-setup.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log('PASS: Google-only setup request, no URL bypass, verified recovery callback, mismatch rejected, password saved, parent remains locked until password entered, child selection')
} finally { await browser.close() }
