import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
const require = createRequire(process.argv[2] || import.meta.url)
const { chromium } = require('playwright')
const browser = await chromium.launch({ headless: true, channel: 'chrome' })
try {
  const context = await browser.newContext({ viewport: { width: 810, height: 1080 }, hasTouch: true })
  await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
  const page = await context.newPage()
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5191/')
  await page.getByLabel('Parent password').fill('wrong')
  await page.getByRole('button', { name: 'Unlock parent controls' }).click()
  await page.getByRole('alert').waitFor()
  assert.equal(await page.getByRole('button', { name: /^Zinc/ }).count(), 0)
  const unlock = async () => {
    await page.getByLabel('Parent password').fill('test-parent-password')
    await page.getByRole('button', { name: 'Unlock parent controls' }).click()
    await page.getByRole('heading', { name: 'Family profiles' }).waitFor()
  }
  await unlock()
  await page.getByRole('button', { name: /^Zinc/ }).click()
  await page.getByRole('heading', { name: 'Your courses' }).waitFor()
  assert.equal(await page.locator('.account-email').innerText(), 'Zinc')
  await page.reload()
  await page.getByRole('heading', { name: 'Your courses' }).waitFor()
  assert.equal(await page.locator('.account-email').innerText(), 'Zinc')
  await page.screenshot({ path: '/private/tmp/home-scholar-child-profile.png', fullPage: true })
  await page.goto('http://127.0.0.1:5191/parent')
  await page.getByLabel('Parent password').waitFor()
  assert.equal(await page.getByRole('button', { name: 'Sign out of family account' }).count(), 0)
  await unlock()
  await page.getByRole('button', { name: /^Rush/ }).click()
  await page.getByRole('heading', { name: 'Your courses' }).waitFor()
  assert.equal(await page.locator('.account-email').innerText(), 'Rush')
  await page.getByRole('link', { name: 'Parent', exact: true }).click(); await unlock()
  await page.getByRole('button', { name: /^Parent Parent$/ }).click()
  await page.getByRole('heading', { name: 'Your courses' }).waitFor()
  assert.equal(await page.locator('.account-email').innerText(), 'Parent')
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')) })
  await page.waitForFunction(() => document.querySelector('.account-email')?.textContent === 'Rush')
  await page.getByRole('link', { name: 'Parent', exact: true }).click()
  await page.getByLabel('Parent password').waitFor()
  await page.screenshot({ path: '/private/tmp/home-scholar-parent-lock.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log('PASS: wrong password, first selection, reload persistence, direct parent URL, protected sign-out, child switch, background relock; no page errors')
} finally { await browser.close() }
